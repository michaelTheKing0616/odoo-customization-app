def np_section(cid: str) -> list[str]:
    if cid not in _np:
        _np[cid] = _np_section(cid)
    return _np[cid]


def _np_section(cid: str) -> list[str]:
    pat = re.compile(rf"^#{{2,4}} {re.escape(cid)}(?:\b| —|\s)")
    files = sorted((NP_DIR / "cards").glob("*.md")) + sorted(NP_DIR.glob("*.md"))
    for f in files:
        ls = lines(f)
        for i, line in enumerate(ls):
            if pat.match(line):
                level = len(line) - len(line.lstrip("#"))
                body = [line]
                for nxt in ls[i + 1:]:
                    if re.match(rf"^#{{1,{level}}} ", nxt):
                        break
                    body.append(nxt)
                return [f"{f.relative_to(ROOT)}"] + body
        for line in ls:
            if re.match(rf"^\|\s*{re.escape(cid)}\s*\|", line):
                return [f"{f.relative_to(ROOT)}", line]
    return []


def np_field(section: list[str], name: str) -> str:
    for line in section:
        m = re.match(rf"^-\s*\*\*{name}[^*]*:\*\*\s*(.*)", line)
        if m:
            return m.group(1).strip()
    return ""


