def acs_for_row(row: dict) -> tuple[list[str], list[str]]:
    """Verbatim AC texts and context refs for one ledger row."""
    src, acs, ctx = row["source_section"], [], []
    for seg in [s.strip() for s in src.split(";")]:
        path = CSS if "CONFIG_SUITE_SPEC" in seg else DT if "DESIGN_TOUCHES" in seg else HANDOVER
        for n in re.findall(r"\bL(\d{2,4})\b", seg):
            text = lines(path)[int(n) - 1] if int(n) <= len(lines(path)) else ""
            if text.strip():
                acs.append(f"{clean(text)} (source: {path.name} L{n})")
                ctx.append(f"`sed -n '{n}p' {path.relative_to(ROOT)}`")
        m = re.search(r"BRIDGE_RUNNER_SPEC (CR|Bridge|LLM|AI)\D*(\d+)", seg)
        if m and (m.group(1), int(m.group(2))) in BRSI:
            acs.append(f"{BRSI[(m.group(1), int(m.group(2)))]} (source: BRIDGE_RUNNER_SPEC {m.group(1)} {m.group(2)})")
        m = re.match(r"FA ([A-Z]\d+)\b", seg)
        if m and m.group(1) in FAI:
            acs.append(f"{FAI[m.group(1)]} (source: FEATURE_AUDIT {m.group(1)})")
    m = re.match(r"idea (\d+)", row["one_line"])
    if row["ID"].startswith("SUITE-") and m and int(m.group(1)) in SUITE:
        acs.append(f"{SUITE[int(m.group(1))]} (source: CONFIG_SUITE_SPEC idea {m.group(1)})")
        ctx.append(f"`rg -n '^{m.group(1)}\\. \\*\\*' docs/specs/CONFIG_SUITE_SPEC.md`")
    m = re.match(r"touch (\d+)", row["one_line"])
    if m and int(m.group(1)) in TOUCH:
        acs.append(f"{TOUCH[int(m.group(1))]} (source: DESIGN_TOUCHES touch {m.group(1)})")
        ctx.append(f"`rg -n '^{m.group(1)}\\. \\*\\*' docs/DESIGN_TOUCHES.md`")
    if not acs:
        acs.append(f"{row['one_line']} (source: ledger {row['ID']}, {src})")
    return acs, ctx


def card_type(cid: str, rows: list[dict]) -> str:
    if cid.startswith("V-"):
        return "verify"
    if cid.startswith("REG-") or cid.endswith("-REG"):
        return "regression"
    if cid.startswith("L2-PROVE"):
        return "prove-live"
    if re.match(r"UI-.*-SPEC$", cid) or cid in ("UI-REF-STUDY", "UI-AUDIT-ALL"):
        return "ui-spec"
    if re.match(r"UI-(.*-BUILD$|S-|F\d|SP-)", cid):
        return "ui-build"
    if cid.startswith(("DOC-", "ADR-", "NP-", "FA-S")) or cid in ("BL-08", "B0-INV"):
        return "docs"
    types = collections.Counter(r["type"] for r in rows if r["type"] in
                                {"build", "rebuild", "test", "security", "verify", "docs", "prove-live", "decision"})
    t = types.most_common(1)[0][0] if types else "build"
    return {"security": "test"}.get(t, t)


def score_card(cid: str, rows: list[dict], text: str, ctype: str, guarded: bool) -> tuple[int, str]:
    pressures = [re.search(r"pressure (\d+)", r["one_line"]) for r in rows]
    sec = []
    s = np_section(cid)
    m = re.search(r"C(\d) U(\d) F(\d) K(\d) V(\d) I(\d)", np_field(s, "Pressure")) if s else None
    if m:
        sec = [min(2, int(x)) for x in m.groups()]
    t = text.lower()
    if not sec:
        c = 2 if re.search(r"money|write gate|auth|tenan|ir\.access|alembic|secret|password|payment|billing|autonom|encrypt|delete|drop", t) \
            else 1 if re.search(r"write|install|security|undo|snapshot|approv|redact|pii", t) else 0
        u = 0 if ctype in ("regression", "verify", "docs") else 2 if re.search(r"\bbig\b|premium|bold|frontier", t) else 1
        f = 0 if ctype == "docs" else 2 if re.search(r"every|all routes|across|sweep|each page|whole", t) else 1
        k = 0 if ctype in ("regression", "verify", "docs", "prove-live") else 2 if any(r["status_label_today"].startswith("Missing") for r in rows) else 1
        v = 2 if re.search(r"\blive\b|17-20|17–20", t) or ctype == "prove-live" else 1 if re.search(r"odoo|view|field|model|module|install", t) else 0
        i = 2 if re.search(r"delete|drop|migration|alembic|cleanup|deploy", t) else 1 if re.search(r"write|install|apply", t) else 0
        sec = [c, u, f, k, v, i]
    if any(p and int(p.group(1)) >= 14 for p in pressures):
        while sum(sec) < 6:
            sec[sec.index(min(sec))] += 1
    if guarded:
        sec[0] = 2
        while sum(sec) < 6:
            sec[sec.index(min(sec))] += 1
    score = sum(sec)
    return score, "{} (C{} U{} F{} K{} V{} I{})".format(score, *sec)


def tier(score: int) -> str:
    return "L1" if score <= 2 else "L2" if score <= 5 else "L3"


def budget(ctype: str, score: int, flagship: bool) -> str:
    if ctype in ("docs", "decision", "verify"):
        return "XS" if score <= 2 else "S"
    if ctype == "regression":
        return "S"
    if ctype == "ui-spec":
        return "M"
    if ctype == "ui-build":
        return "L" if flagship else "M"
    return "S" if score <= 2 else "M" if score <= 5 else "L"


def slug(cid: str) -> str:
    return cid.lower().replace("-", "_").replace(".", "_")


def feature(cid: str) -> tuple[list[str], str]:
    best = ""
    for prefix in FEATURE:
        if cid.startswith(prefix) and len(prefix) > len(best):
            best = prefix
    return FEATURE.get(best, ([], "api"))


def phase_of(cid: str, pm: dict) -> int:
    best, phase = "", None
    for prefix, ph in pm.items():
        if not prefix.startswith("_") and cid.startswith(prefix) and len(prefix) > len(best):
            best, phase = prefix, ph
    return phase


