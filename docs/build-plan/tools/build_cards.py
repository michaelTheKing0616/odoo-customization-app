def main() -> int:
    args = sys.argv[1:]
    only = set(args[args.index("--only") + 1].split(",")) if "--only" in args else None
    force = "--force-generated" in args
    rows = list(csv.DictReader(LEDGER.open()))
    fields = list(rows[0].keys())
    pm = json.loads((PLAN / "phase_map.json").read_text())
    existing = {p.stem: p for p in CARDS.glob("phase-*/*.md")}
    planned = {c for r in rows for c in r["card_ids"].split(";") if c and "*" not in c} - DOC_TARGETS
    pm["_known"] = planned | set(existing)
    for r in rows:  # wildcard rows -> concrete cards
        if r["ID"] in WILDCARD_REPOINT:
            r["card_ids"] = WILDCARD_REPOINT[r["ID"]]
        if r["ID"] in FAMILY_ROWS:
            fam = FAMILY_ROWS[r["ID"]]
            r["card_ids"] = ";".join(sorted(c for c in planned if c.startswith(fam)))
    family: dict[str, list[tuple[str, str]]] = collections.defaultdict(list)
    for r in rows:
        if r["ID"] in FAMILY_ROWS:
            for c in r["card_ids"].split(";"):
                family[c].append((r["ID"], r["one_line"] + f" (source: {r['source_section']})" if r["ID"] == "TOUCH-SPEC"
                                  else acs_for_row(r)[0][0]))
    by_card: dict[str, list[dict]] = collections.defaultdict(list)
    for r in rows:
        for c in r["card_ids"].split(";"):
            if c:
                by_card[c].append(r)
    written = 0
    for cid in sorted(planned):
        if only and cid not in only:
            continue
        path = existing.get(cid)
        if path and not (force and MARK in path.read_text()):
            continue
        phase = phase_of(cid, pm)
        if phase is None:
            print(f"skip {cid}: no phase prefix")
            continue
        main_rows = [r for r in by_card[cid] if r["ID"] not in FAMILY_ROWS]
        text = render(cid, main_rows or by_card[cid], pm, family.get(cid, []))
        text = text.replace(f"Ledger IDs: {';'.join(r['ID'] for r in (main_rows or by_card[cid]))}",
                            "Ledger IDs: " + ";".join(r["ID"] for r in by_card[cid]))
        out = CARDS / f"phase-{phase}" / f"{cid}.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        written += 1
    with LEDGER.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    counts: dict[int, collections.Counter] = collections.defaultdict(collections.Counter)
    caps: collections.Counter = collections.Counter()
    tiers: dict[int, collections.Counter] = collections.defaultdict(collections.Counter)
    classes = json.loads((PLAN / "budget.json").read_text())["classes"]
    for p in CARDS.glob("phase-*/*.md"):
        body = p.read_text()
        ph = int(p.parent.name.split("-")[1])
        t = re.search(r"^Type: (\S+)", body, re.M)
        counts[ph][t.group(1) if t else "?"] += 1
        b = re.search(r"Budget: (XS|S|M|L|XL)\b", body)
        caps[ph] += sum(classes[b.group(1)].values()) if b else 0
        w = re.search(r"Worker: (L\d|E\d)", body)
        tiers[ph][w.group(1) if w else "?"] += 1
    rep = ["# Cards per phase (written by tools/build_cards.py)", "",
           "Cap = sum of class caps (worker + tester + reviewer, `budget.json`) in millions of cost-weighted tokens; "
           "expected spend is lower (most cards stop well under cap) and is measured by the pilot.", "",
           "| Phase | Cards | L1 / L2 / L3 / E | Cap (M) | By type |", "|---|---|---|---|---|"]
    for ph in sorted(counts):
        tr = tiers[ph]
        rep.append(f"| {ph} | {sum(counts[ph].values())} | {tr['L1']} / {tr['L2']} / {tr['L3']} / {tr['E1'] + tr['E2']} | "
                   f"{caps[ph] / 1e6:.0f} | " + ", ".join(f"{k} {v}" for k, v in counts[ph].most_common()) + " |")
    rep.append(f"| all | {sum(sum(c.values()) for c in counts.values())} | | {sum(caps.values()) / 1e6:.0f} | |")
    (PLAN / "coverage" / "phases.md").write_text("\n".join(rep) + "\n")
    print(f"cards written {written}; total {sum(sum(c.values()) for c in counts.values())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
