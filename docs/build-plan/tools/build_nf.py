#!/usr/bin/env python3
"""Generate the new-feature (NF) epic cards, ledger rows, phase_map prefixes, DEC rows and
NEW_FEATURES_INDEX.md from the data in tools/nf_data.py (Tope's new-features brief, 22 Oct).

Usage: python3 docs/build-plan/tools/build_nf.py [--dry-run]

Side effects (all under docs/build-plan/):
- writes cards/phase-N/<ID>.md for NF cards only; an existing file is rewritten only while it
  still carries NF_MARKER (Prep edits that delete the marker are never overwritten);
- replaces every NF-* row in ledger.csv (other rows untouched, order kept);
- appends missing NF prefixes to phase_map.json (text insert, existing lines untouched);
- appends the NF DEC section to 09_DECISIONS_FOR_TOPE.md once;
- adds the closing dependency to the existing umbrella cards listed in nf_data.UMBRELLAS;
- writes NEW_FEATURES_INDEX.md.
"""
