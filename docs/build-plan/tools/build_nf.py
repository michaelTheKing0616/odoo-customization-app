def render(card: dict, epic: dict) -> str:
    total, breakdown = score_text(card["score"])
    t = tier(total)
    routing = f"Worker: {t} (grok-4.7-xhigh) · Tester: T0 + L2 separate session · Reviewer: {t} separate session · Score: {total} ({breakdown})"
    if total >= 10:
        routing += " · E1 oracle review"
    kind = card["kind"]
    steps = [s.replace("{slug}", epic["slug"].replace("-", "_")).replace("{card}", card["id"]) for s in KIND_STEPS[kind]] + card.get("steps", [])
    stop = STOP + (" " + card["stop"] if card.get("stop") else "")
    gate_kind = card.get("gate_kind") or ("ui" if kind in ("ui", "vis") else "live" if kind == "live" else "default")
    gate = GATE[gate_kind].replace("{screen}", epic["slug"])
    if card.get("gate_dec"):
        dec, why = card["gate_dec"]
        gate = f"A ({dec}: {why}). Starts only after Tope answers {dec}; then: " + gate
    rollback = ROLLBACK[card.get("rollback", "storage" if kind == "storage" else "default")]
    lines = [
        NF_MARKER,
        f"# {card['id']}: {card['title']}",
        "",
        f"ID: {card['id']}",
        f"Title: {card['title']}",
        "Status: todo",
        f"Phase: {epic['phase']}",
        f"Priority: {epic['prio']}",
        f"Type: {card['type']}",
        f"Owner: {card['owner']}",
        f"TOKEN CHARTER: docs/build-plan/01_TOKEN_CHARTER.md applies. Budget: {card['budget']} (caps in budget.json). Stop at 80%.",
        f"Ledger IDs: {card['ledger']}",
        f"Depends on: {', '.join(card['deps']) if card['deps'] else 'none (phase order applies)'}",
        f"Routing: {routing}",
        "Context pack:",
        f"- docs/build-plan/new-features/{epic['group']}.md §{epic['code']} (sections 1–7)",
        "- docs/build-plan/new-features/00_BASELINE.md (B1–B5)",
        "- docs/build-plan/FACTS.md",
    ]
    lines += [f"- {c}" for c in card.get("context", [])]
    lines.append("File allow-list:")
    lines += [allow_line(a) for a in card["allow"]]
    lines.append(f"Goal: {card['goal']}")
    lines.append("Steps:")
    lines += [f"{i}. {s}" for i, s in enumerate(steps + [stop], 1)]
    lines.append("Acceptance criteria:")
    lines += [f"- AC{i}: {a}" for i, a in enumerate(card["acs"], 1)]
    lines += ["Decision table:", "", "| Input / evidence | Expected |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in card["table"]]
    lines += ["", "Test plan:"]
    lines += [f"- `{c}` → {e}" for c, e in card["tests"]]
    if total >= 6:
        lines.append(f"Elite design notes: {card['elite']}")
        lines.append(f"Oracle tests: {card['oracle']}")
    lines += [
        f"Gate: {gate}",
        f"Evidence to log: {EVIDENCE}",
        f"Rollback: {rollback}",
        f"Definition of Done: {DOD}",
        "",
    ]
    return "\n".join(lines)


def build_cards() -> tuple[list[dict], list[dict]]:
    """Expand every epic into its card list; returns (cards, epics)."""
    all_cards: list[dict] = []
    for epic in D.EPICS:
        cards = D.expand(epic)
        epic["cards"] = cards
        all_cards.extend(cards)
    return all_cards, D.EPICS


def ledger_rows(cards: list[dict], epics: list[dict]) -> list[dict]:
    rows = []
    for epic in epics:
        ids = [c["id"] for c in epic["cards"]]
        rows.append({
            "ID": f"NF-EPIC-{epic['code']}", "source_section": f"user brief 22 Oct; new-features/{epic['group']}.md#{epic['code'].lower()}",
            "one_line": f"Epic {epic['name']}: {epic['one_line']}", "type": "build", "priority": epic["prio"],
            "status_label_today": epic.get("status", "Missing"), "card_ids": ";".join(ids),
            "tope_decision": ";".join(["DEC-050"] + epic.get("decs", [])),
        })
        for c in epic["cards"]:
            decs = ["DEC-050"] + ([c["gate_dec"][0]] if c.get("gate_dec") else [])
            rows.append({
                "ID": f"NF-{c['id']}", "source_section": f"user brief 22 Oct; new-features/{epic['group']}.md#{epic['code'].lower()}",
                "one_line": c["title"], "type": c["type"], "priority": epic["prio"], "status_label_today": "Missing",
                "card_ids": c["id"], "tope_decision": ";".join(dict.fromkeys(decs)),
            })
    return rows


def write_ledger(rows: list[dict], dry: bool) -> int:
    path = PLAN / "ledger.csv"
    text = path.read_text()
    reader = csv.DictReader(io.StringIO(text))
    fields = reader.fieldnames
    kept = [r for r in reader if not r["ID"].startswith("NF-")]
    out = io.StringIO()
    w = csv.DictWriter(out, fieldnames=fields, lineterminator="\r\n")
    w.writeheader()
    w.writerows(kept + rows)
    if not dry:
        path.write_text(out.getvalue())
    return len(rows)


def write_phase_map(epics: list[dict], dry: bool) -> list[str]:
    path = PLAN / "phase_map.json"
    text = path.read_text()
    added = [(f"{e['code']}-", e["phase"]) for e in epics if f"\"{e['code']}-\"" not in text]
    if added and not dry:
        body = text.rstrip()
        assert body.endswith("}")
        body = body[:-1].rstrip()
        block = ",\n\n" + ",\n".join(f'  "{k}": {v}' for k, v in added)
        path.write_text(body + block + "\n}\n")
    return [k for k, _ in added]


def write_umbrellas(dry: bool) -> list[str]:
    done = []
    for cid, (deps, note) in D.UMBRELLAS.items():
        path = next((PLAN / "cards").rglob(f"{cid}.md"), None)
        if path is None:
            raise SystemExit(f"umbrella card {cid} not found")
        text = path.read_text()
        m = re.search(r"^Depends on: (.*)$", text, re.M)
        current = m.group(1).strip()
        have = [] if current.startswith("none") else [d.strip() for d in current.split(",")]
        new = have + [d for d in deps if d not in have]
        text = text[: m.start()] + "Depends on: " + (", ".join(new) if new else current) + text[m.end():]
        line = f"- {note}"
        if line not in text:
            text = text.replace("Context pack:\n", "Context pack:\n" + line + "\n", 1)
        if not dry:
            path.write_text(text)
        done.append(cid)
    return done


def write_decisions(dry: bool) -> bool:
    path = PLAN / "09_DECISIONS_FOR_TOPE.md"
    text = path.read_text()
    if D.DEC_HEADER in text:
        return False
    block = [D.DEC_HEADER, D.DEC_INTRO, "", "| ID | Decision | Default (recommended) | Blocks |", "|---|---|---|---|"]
    block += [f"| {d} | {q} | {a} | {b} |" for d, q, a, b in D.DECS]
    if not dry:
        path.write_text(text.rstrip() + "\n\n" + "\n".join(block) + "\n")
    return True


def write_index(epics: list[dict], dry: bool) -> None:
    rows = []
    for e in epics:
        days = sum(BUDGET_DAYS[c["budget"]] for c in e["cards"])
        rows.append((e, days, round(e["value"] / days * 10, 2)))
    ranked = sorted(rows, key=lambda r: (-r[2], r[0]["code"]))
    out = [D.INDEX_HEAD, "", "## Ranked list (value ÷ effort)", "",
           "Value is 1–5 (reasoning in the row). Effort is card-days (XS 0.25, S 0.5, M 1, L 2), summed from this epic's cards. Ratio = value ÷ effort × 10. SCAN is the enabler that 9 epics need, so it ships first whatever its ratio.", "",
           "| Rank | Epic | Phase | Value | Cards | Effort (card-days) | Ratio | Why this value |", "|---|---|---|---|---|---|---|---|"]
    for i, (e, days, ratio) in enumerate(ranked, 1):
        out.append(f"| {i} | [{e['code']}](new-features/{e['group']}.md#{e['code'].lower()}) {e['name']} | {e['phase']} | {e['value']} | {len(e['cards'])} | {days:g} | {ratio} | {e['why']} |")
    total_cards = sum(len(e["cards"]) for e in epics)
    total_days = sum(r[1] for r in rows)
    out += ["", f"Totals: {len(epics)} epics, {total_cards} cards, {total_days:g} card-days.", ""]
    out += D.INDEX_TAIL
    if not dry:
        (PLAN / "NEW_FEATURES_INDEX.md").write_text("\n".join(out) + "\n")


def main() -> None:
    dry = "--dry-run" in sys.argv
    cards, epics = build_cards()
    seen: set[str] = set()
    written = skipped = 0
    for c in cards:
        assert c["id"] not in seen, f"duplicate card id {c['id']}"
        seen.add(c["id"])
        epic = next(e for e in epics if c in e["cards"])
        path = PLAN / "cards" / f"phase-{epic['phase']}" / f"{c['id']}.md"
        body = render(c, epic)
        n = len(body.splitlines())
        assert n <= 150, f"{c['id']} has {n} lines"
        if path.exists() and NF_MARKER not in path.read_text():
            skipped += 1
            continue
        if not dry:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)
        written += 1
    nrows = write_ledger(ledger_rows(cards, epics), dry)
    prefixes = write_phase_map(epics, dry)
    umbrellas = write_umbrellas(dry)
    decs = write_decisions(dry)
    write_index(epics, dry)
    print(f"cards written {written}, kept (Prep-edited) {skipped}; ledger NF rows {nrows}; "
          f"phase_map +{len(prefixes)}; umbrellas {len(umbrellas)}; DEC section {'added' if decs else 'present'}"
          f"{' (dry run)' if dry else ''}")


if __name__ == "__main__":
    main()
