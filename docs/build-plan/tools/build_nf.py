NF_MARKER = "<!-- NF: generated by tools/build_nf.py; Prep may edit (then delete this line) -->"
BUDGET_DAYS = {"XS": 0.25, "S": 0.5, "M": 1.0, "L": 2.0}
FORBIDDEN_PORTS = "3002, 8001, 8002, 8012, 5433, 5436, 8069–8073, 11434"


def tier(score: int) -> str:
    return "L1" if score <= 2 else "L2" if score <= 5 else "L3"


def exists(rel: str) -> bool:
    return (ROOT / rel).exists()


def allow_line(rel: str) -> str:
    return f"- {rel}" if exists(rel) or rel.endswith("/") and (ROOT / rel).is_dir() else f"- {rel} (new)"


def score_text(s: tuple[int, ...]) -> tuple[int, str]:
    labels = "CUFKVI"
    return sum(s), " ".join(f"{labels[i]}{v}" for i, v in enumerate(s))


