FREE_PLANS = {"free_solo", "project_pass"}


def prepared_footer(*, plan_id: str, white_label: bool, hide: bool) -> str | None:
    """Touch 156: optional footer. Free plans always show it; paid plans may remove it; white-label never shows Ingenium."""
    if white_label:
        return None
    if hide and plan_id not in FREE_PLANS:
        return None
    return PREPARED_FOOTER


def handbook(flow_id: str, v: dict[str, Any], score: dict[str, Any] | None = None, footer: str | None = PREPARED_FOOTER) -> str:
    d = v["defn"]
    rows = "\n".join(f"| {m['remote']} | {m['odoo']} | {m.get('transform', 'none')} |" for m in d.get("mapping") or [] if m.get("odoo"))
    return f"""![](docs/arch.svg)

# {flow_id} — integration handbook

Version {v["n"]} · hash `{v["hash"]}` · {"money flow (second approver, reconciliation)" if v.get("money") else "no money fields"}

## What it does
{d.get("connector")} **{d.get("entity", "")}** → Odoo **{d.get("odoo_model")}** ({d.get("direction", "in")}).

## Field map
| App field | Odoo field | Change on the way |
|---|---|---|
{rows}

## Run it
- Middleware: copy `.env.example` to `.env`, fill it, `docker build -t {_slug(flow_id)} . && docker run --env-file .env -p 8080:8080 {_slug(flow_id)}`. Health: `GET /health`.
- Odoo module: install in a test database first, set the two `ingenium_bridge.*` system parameters, then enable the cron.

## When something fails
Retries back off up to 5 times; then the event goes to the dead-letter inbox in Bridge, where you can fix and replay it.
{"" if not score else f"## Integration score{chr(10)}{score['score']}/100 ({score['grade']})"}
{"" if not footer else f"{chr(10)}---{chr(10)}_{footer}_{chr(10)}"}"""


def check_files(files: dict[str, str]) -> list[str]:
    errs = []
    for path, src in files.items():
        if path.endswith(".py"):
            try:
                ast.parse(src)
            except SyntaxError as exc:
                errs.append(f"{path}: {exc.msg} line {exc.lineno}")
        if re.search(r"\b(sk|pk)_(live|test)_[A-Za-z0-9]{6,}|Bearer [A-Za-z0-9._-]{20,}", src):
            errs.append(f"{path}: looks like a secret is inlined")
    return errs


def build_zip(flow_id: str, v: dict[str, Any], kind: str, odoo_major: int = 18, score: dict[str, Any] | None = None, footer: str | None = PREPARED_FOOTER) -> tuple[bytes, list[str]]:
    files = service_files(flow_id, v) if kind == "service" else module_files(flow_id, v, odoo_major)
    files["HANDBOOK.md"] = handbook(flow_id, v, score, footer)
    files["docs/arch.svg"] = ARCH_DRAWING_SVG
    errs = check_files(files)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p, s in files.items():
            z.writestr(p, s)
    return buf.getvalue(), errs
