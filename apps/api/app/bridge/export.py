from app.bridge.gallery import BY_KEY


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")[:40] or "flow"


def _mapping_py(mapping: list[dict[str, Any]]) -> str:
    pairs = [(m["remote"], m["odoo"], m.get("transform", "none")) for m in mapping if m.get("odoo")]
    return "MAPPING = " + json.dumps(pairs, indent=1) + "\n"


TRANSFORMS_PY = '''
from datetime import date, datetime


def transform(name, v):
    if v is None or name == "none":
        return v
    if name == "trim":
        return str(v).strip()
    if name == "lower":
        return str(v).lower()
    if name == "upper":
        return str(v).upper()
    if name == "to_int":
        return int(float(v))
    if name == "to_float":
        return float(v)
    if name == "cents_to_units":
        return round(float(v) / 100, 2)
    if name == "to_date":
        s = str(v)
        return (datetime.fromisoformat(s.replace("Z", "+00:00")).date() if "T" in s else date.fromisoformat(s)).isoformat()
    if name == "to_datetime":
        return datetime.fromisoformat(str(v).replace("Z", "+00:00")).strftime("%Y-%m-%d %H:%M:%S")
    if name == "to_bool":
        return str(v).strip().lower() in ("1", "true", "yes", "y", "on")
    raise ValueError(name)


def map_record(rec):
    return {o: transform(t, rec.get(r)) for r, o, t in MAPPING}
'''


def service_files(flow_id: str, v: dict[str, Any]) -> dict[str, str]:
    d = v["defn"]
    c = BY_KEY.get(d.get("connector", ""), None)
    sig = (c.webhook_signature if c else None) or ""
    app_py = f'''"""Generated by Ingenium Bridge: flow {flow_id} v{v["n"]} ({v["hash"]}). You own this code."""
import base64, hashlib, hmac, json, os, time
import xmlrpc.client
from fastapi import FastAPI, Header, HTTPException, Request

{_mapping_py(d.get("mapping") or [])}{TRANSFORMS_PY}
ODOO_URL, ODOO_DB = os.environ["ODOO_URL"], os.environ["ODOO_DB"]
ODOO_USER, ODOO_KEY = os.environ["ODOO_USER"], os.environ["ODOO_API_KEY"]
WEBHOOK_SECRET = os.environ.get("WEBHOOK_SECRET", "")
MODEL = {json.dumps(d.get("odoo_model", ""))}
SIGNATURE = {json.dumps(sig)}
SEEN = set()  # idempotency (swap for Redis/DB in production)
app = FastAPI()


def verify(body, header):
    if not WEBHOOK_SECRET:
        return False
    if SIGNATURE == "hmac-sha256-base64":
        want = base64.b64encode(hmac.new(WEBHOOK_SECRET.encode(), body, hashlib.sha256).digest()).decode()
    elif SIGNATURE == "hmac-sha512-hex":
        want = hmac.new(WEBHOOK_SECRET.encode(), body, hashlib.sha512).hexdigest()
    elif SIGNATURE == "hmac-sha256-hex":
        want = hmac.new(WEBHOOK_SECRET.encode(), body, hashlib.sha256).hexdigest()
    else:
        want = WEBHOOK_SECRET
    return hmac.compare_digest(want, header or "")


def odoo():
    uid = xmlrpc.client.ServerProxy(ODOO_URL + "/xmlrpc/2/common").authenticate(ODOO_DB, ODOO_USER, ODOO_KEY, {{}})
    return uid, xmlrpc.client.ServerProxy(ODOO_URL + "/xmlrpc/2/object", allow_none=True)


@app.get("/health")
def health():
    return {{"ok": True, "flow": {json.dumps(flow_id)}, "version": {v["n"]}}}


@app.post("/webhook")
async def webhook(request: Request, x_signature: str = Header(default="")):
    body = await request.body()
    if not verify(body, x_signature):
        raise HTTPException(401, "bad signature")
    key = hashlib.sha256(body).hexdigest()
    if key in SEEN:
        return {{"duplicate": True}}
    rec = json.loads(body)
    vals = map_record(rec)
    for attempt in range(5):
        try:
            uid, m = odoo()
            rid = m.execute_kw(ODOO_DB, uid, ODOO_KEY, MODEL, "create", [vals])
            SEEN.add(key)
            print(json.dumps({{"at": time.time(), "status": "ok", "id": rid}}))
            return {{"id": rid}}
        except Exception as exc:
            print(json.dumps({{"at": time.time(), "status": "retry", "attempt": attempt, "error": type(exc).__name__}}))
            time.sleep(min(60, 2 ** attempt))
    raise HTTPException(503, "Odoo unavailable; retry later")
'''
    files = {
        "app.py": app_py,
        "requirements.txt": "fastapi==0.115.*\nuvicorn==0.30.*\n",
        "Dockerfile": "FROM python:3.12-slim\nWORKDIR /app\nCOPY . .\nRUN pip install --no-cache-dir -r requirements.txt\n"
                      "EXPOSE 8080\nHEALTHCHECK CMD python -c \"import urllib.request;urllib.request.urlopen('http://localhost:8080/health')\"\n"
                      "CMD [\"uvicorn\", \"app:app\", \"--host\", \"0.0.0.0\", \"--port\", \"8080\"]\n",
        ".env.example": "ODOO_URL=https://your.odoo.com\nODOO_DB=\nODOO_USER=\nODOO_API_KEY=\nWEBHOOK_SECRET=\n",
        "test_mapping.py": "from app import map_record, MAPPING\n\n\ndef test_mapping_runs():\n    assert isinstance(map_record({}), dict)\n",
    }
    return files


def module_files(flow_id: str, v: dict[str, Any], odoo_major: int = 18) -> dict[str, str]:
    d = v["defn"]
    name = f"ingenium_bridge_{_slug(flow_id)}"
    model = d.get("odoo_model", "res.partner")
    manifest = {"name": f"Ingenium Bridge: {flow_id}", "version": f"{odoo_major}.0.1.0.0", "license": "LGPL-3",
                "depends": ["base"], "data": ["data/cron.xml"], "installable": True,
                "summary": f"Pulls {d.get('entity')} from {d.get('connector')} into {model} (flow v{v['n']})."}
    py = f'''import json
import logging
import urllib.request

from odoo import api, models

_logger = logging.getLogger(__name__)
{_mapping_py(d.get("mapping") or [])}{TRANSFORMS_PY}

class IngeniumBridgePull(models.AbstractModel):
    _name = "ingenium.bridge.{_slug(flow_id)}"
    _description = "Ingenium Bridge pull: {flow_id}"

    @api.model
    def _cron_pull(self):
        icp = self.env["ir.config_parameter"].sudo()
        url = icp.get_param("ingenium_bridge.{_slug(flow_id)}.url")
        token = icp.get_param("ingenium_bridge.{_slug(flow_id)}.token")
        if not url or not token:
            _logger.info("Bridge {flow_id}: not configured")
            return
        req = urllib.request.Request(url, headers={{"Authorization": "Bearer " + token, "Accept": "application/json"}})
        with urllib.request.urlopen(req, timeout=30) as r:
            rows = json.loads(r.read() or b"[]")
        Model = self.env[{json.dumps(model)}]
        for rec in rows if isinstance(rows, list) else []:
            Model.create(map_record(rec))
'''
    cron = f'''<?xml version="1.0" encoding="utf-8"?>
<odoo>
  <record id="cron_pull" model="ir.cron">
    <field name="name">Ingenium Bridge: {flow_id}</field>
    <field name="model_id" ref="model_ingenium_bridge_{_slug(flow_id)}"/>
    <field name="state">code</field>
    <field name="code">model._cron_pull()</field>
    <field name="interval_number">15</field>
    <field name="interval_type">minutes</field>
    <field name="active" eval="False"/>
  </record>
</odoo>
'''
    return {f"{name}/__manifest__.py": repr(manifest) + "\n", f"{name}/__init__.py": "from . import models\n",
            f"{name}/models/__init__.py": "from . import bridge\n", f"{name}/models/bridge.py": py, f"{name}/data/cron.xml": cron}


