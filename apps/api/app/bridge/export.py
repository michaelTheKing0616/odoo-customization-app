"""Bridge B9 (spec 24-26): generate an owned middleware service, or an Odoo module, plus a
documented code export and handbook, from an approved flow version. Generated code is checked
(ast.parse, no secrets inlined) before it is handed out; secrets are read from env at runtime.
"""
